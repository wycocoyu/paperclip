/** 有骨架的文档键，按页面展示顺序。 */
export const DOCUMENT_SKELETON_KEYS = Object.keys(DOCUMENT_SKELETONS);

export function documentSkeleton(key: string): string | undefined {
  return DOCUMENT_SKELETONS[key];
}
